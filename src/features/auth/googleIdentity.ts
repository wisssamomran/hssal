/**
 * Google Identity Services, loaded on demand.
 *
 * Three rules shape this file:
 *
 * 1. Nothing is fetched until the operator has switched the feature on *and*
 *    filled in a client ID. `googleSignInSettings()` in `lib/config.ts` reads
 *    both from `/api/v1/bootstrap`, and `ready` is the server's own pair of
 *    gates. A button that could only be refused by the API is never drawn, and
 *    a third-party script is never loaded into a page that will not use it.
 *
 * 2. The client ID is not a secret and is not stored here. It is an operator
 *    setting; whatever is compiled into this bundle would outlive the day the
 *    operator changes it — or turns the feature off.
 *
 * 3. The nonce is generated by *this browser before* it asks Google for a
 *    token, handed to Google Identity Services at initialization so Google
 *    signs it into the ID token, and stored only for the current attempt. The
 *    server compares it with the one inside the token, which is what stops a
 *    token captured elsewhere — or an old one replayed from a log — from
 *    signing this person in. It lives in `sessionStorage`, not a module
 *    variable, so a reload of the sign-in card cannot strand a pending attempt.
 */

import { googleSignInSettings } from '@/core/config';

const SCRIPT_SRC = 'https://accounts.google.com/gsi/client';
const NONCE_KEY = 'hassal_google_nonce';

/** The slice of the GIS API this file uses. */
interface GoogleAccountsId {
  initialize: (config: {
    client_id: string;
    nonce?: string;
    auto_select?: boolean;
    cancel_on_tap_outside?: boolean;
    callback: (response: { credential?: string }) => void;
  }) => void;
  renderButton: (
    parent: HTMLElement,
    options: {
      type?: 'standard' | 'icon' | 'blank';
      theme?: 'filled' | 'outline' | 'filled_black';
      size?: 'large' | 'medium' | 'small';
      text?: 'signin_with' | 'signup_with' | 'continue_with';
      shape?: 'rectangular' | 'pill' | 'circle' | 'square';
      logo_alignment?: 'left' | 'center';
      width?: number;
      locale?: string;
    }
  ) => void;
}

declare global {
  interface Window {
    google?: { accounts?: { id?: GoogleAccountsId } };
  }
}

let scriptPromise: Promise<void> | null = null;

/**
 * Google's own rule: `initialize()` describes the page, not a button, and
 * calling it again makes the library log that it was called multiple times.
 * Under React that happened on every reopen of the sign-in card — and on mount
 * twice in development, because the tree is rendered, torn down and rendered
 * again to catch exactly this kind of mistake.
 *
 * So the initialization is remembered by the pair that actually matters, the
 * client ID and the nonce: drawing a second button, switching language or
 * switching theme reuses it, and only a rotated nonce — a new attempt after a
 * refusal — asks Google to learn something new.
 */
let initializedFor: string | null = null;

/**
 * The callback Google keeps is the one from the first initialization, so it
 * cannot point straight at a component that may unmount behind it. Every render
 * puts its own handler here, and Google's callback reads through it.
 */
let credentialHandler: ((credential: string) => void) | null = null;

function loadScript(): Promise<void> {
  if (scriptPromise) return scriptPromise;

  scriptPromise = new Promise<void>((resolve, reject) => {
    if (window.google?.accounts?.id) {
      resolve();
      return;
    }

    const existing = document.querySelector<HTMLScriptElement>(`script[src^="${SCRIPT_SRC}"]`);
    const script = existing ?? document.createElement('script');
    if (!existing) {
      script.src = SCRIPT_SRC;
      script.async = true;
      script.defer = true;
      document.head.appendChild(script);
    }
    script.addEventListener('load', () => resolve());
    script.addEventListener('error', () => {
      // A blocked or unreachable Google must not leave a retried click hanging:
      // drop the memoised promise so the next attempt loads again.
      scriptPromise = null;
      reject(new Error('google-script'));
    });
  });

  return scriptPromise;
}

/** 24 random bytes, base64url — 32 characters, inside the API's 16..128 range. */
function randomNonce(): string {
  const bytes = new Uint8Array(24);
  crypto.getRandomValues(bytes);
  let binary = '';
  bytes.forEach((byte) => {
    binary += String.fromCharCode(byte);
  });
  return btoa(binary).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
}

/** The nonce for the current attempt, created once and kept across a reload. */
export function signInNonce(): string {
  try {
    const stored = sessionStorage.getItem(NONCE_KEY);
    if (stored && stored.length >= 16) return stored;
  } catch {
    // Ignore storage denial in restricted iframes.
  }
  const created = randomNonce();
  try {
    sessionStorage.setItem(NONCE_KEY, created);
  } catch {
    // Ignore storage denial in restricted iframes.
  }
  return created;
}

/** A fresh nonce for a new attempt; the old token is worthless after this. */
export function rotateSignInNonce(): string {
  const created = randomNonce();
  try {
    sessionStorage.setItem(NONCE_KEY, created);
  } catch {
    // Ignore storage denial in restricted iframes.
  }
  return created;
}

export function clearSignInNonce(): void {
  try {
    sessionStorage.removeItem(NONCE_KEY);
  } catch {
    // Ignore storage denial in restricted iframes.
  }
}

/**
 * Draw Google's own button into `container`, calling back with the raw ID
 * token. The token is forwarded to `POST /api/v1/auth/google` by the caller —
 * this file deliberately knows nothing about sessions or tokens.
 *
 * Resolves to false when the feature is not ready, so a caller can hide the
 * slot instead of showing a broken button.
 */
export async function renderGoogleSignInButton(options: {
  container: HTMLElement;
  locale: 'ar' | 'en';
  dark: boolean;
  onCredential: (credential: string) => void;
}): Promise<boolean> {
  const settings = googleSignInSettings();
  if (!settings.ready) return false;

  try {
    await loadScript();
  } catch {
    return false;
  }

  const id = window.google?.accounts?.id;
  if (!id) return false;

  const nonce = signInNonce();
  credentialHandler = options.onCredential;

  // Google is told once about a given client ID and nonce; the button below can
  // be drawn again without it, which is what a language or theme switch does.
  const initializedKey = `${settings.clientId}:${nonce}`;
  if (initializedFor !== initializedKey) {
    id.initialize({
      client_id: settings.clientId,
      nonce,
      auto_select: false,
      cancel_on_tap_outside: true,
      callback: (response) => {
        const credential = response?.credential;
        if (credential) credentialHandler?.(credential);
      },
    });
    initializedFor = initializedKey;
  }

  options.container.innerHTML = '';
  id.renderButton(options.container, {
    type: 'standard',
    theme: options.dark ? 'filled_black' : 'outline',
    size: 'large',
    shape: 'pill',
    logo_alignment: 'left',
    // Google localizes its own button label from this; the client does not
    // translate Google's brand copy.
    locale: options.locale,
    text: 'signin_with',
  });

  // Google renders an iframe with its own intrinsic width. Without this the
  // button overflows a 320px phone screen, which is the exact device a Yemeni
  // buyer is most likely to be on.
  const frame = options.container.querySelector('iframe');
  if (frame) {
    frame.style.maxWidth = '100%';
  }

  return true;
}
